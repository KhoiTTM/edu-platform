// Flatten all words for cross-topic exercises
export const allVocabWords: VocabWord[] = vocabTopics.flatMap(t => t.words);

// Get topic by ID
export function getTopicById(id: string): VocabTopic | undefined {
  return vocabTopics.find(t => t.id === id);
}

// Get a random set of distractors (wrong answers) from other topics
export function getDistractors(correctWord: VocabWord, count: number, sameType: boolean = false): VocabWord[] {
  const pool = sameType
    ? allVocabWords.filter(w => w.partOfSpeech === correctWord.partOfSpeech && w.id !== correctWord.id)
    : allVocabWords.filter(w => w.id !== correctWord.id);
  
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
